"""L9: keep Git/bundles truthful. Emits bundle YAML + patches and detects out-of-band changes."""
from __future__ import annotations

import difflib
import json
import re
from typing import Any, Dict, List

from .transform import canonical_hash


def _scalar(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_./-]*", s) and s.lower() not in ("true", "false", "null", "yes", "no", "on", "off"):
        return s
    return json.dumps(s)  # JSON string == valid YAML double-quoted scalar


def to_yaml(obj: Any, indent: int = 0) -> str:
    """Tiny dependency-free YAML emitter (dict/list/scalars) - enough for job settings."""
    pad = "  " * indent
    lines: List[str] = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)) and v:
                lines.append(f"{pad}{k}:")
                lines.append(to_yaml(v, indent + 1))
            else:
                lines.append(f"{pad}{k}: " + ("{}" if v == {} else "[]" if v == [] else _scalar(v)))
    elif isinstance(obj, list):
        for v in obj:
            if isinstance(v, dict) and v:
                inner = to_yaml(v, indent + 1).split("\n")
                lines.append(f"{pad}- " + inner[0].lstrip())
                lines.extend(inner[1:])
            elif isinstance(v, list) and v:
                lines.append(f"{pad}-")
                lines.append(to_yaml(v, indent + 1))
            else:
                lines.append(f"{pad}- {_scalar(v)}")
    else:
        lines.append(f"{pad}{_scalar(obj)}")
    return "\n".join(lines)


def bundle_yaml(resource_key: str, settings: Dict[str, Any]) -> str:
    key = re.sub(r"[^A-Za-z0-9_]+", "_", resource_key).strip("_").lower() or "job"
    body = {"resources": {"jobs": {key: settings}}}
    return "# Generated by Serverless Migration Control Tower - commit to Git so the next `bundle deploy` keeps serverless\n" + to_yaml(body) + "\n"


def settings_diff(old: Dict[str, Any], new: Dict[str, Any], label: str = "job") -> str:
    a = json.dumps(old, indent=2, sort_keys=True).splitlines()
    b = json.dumps(new, indent=2, sort_keys=True).splitlines()
    return "\n".join(difflib.unified_diff(a, b, f"{label} (classic)", f"{label} (serverless)", lineterm=""))


def code_patch(path: str, old: str, new: str) -> str:
    return "\n".join(difflib.unified_diff(old.splitlines(), new.splitlines(), f"a/{path.lstrip('/')}", f"b/{path.lstrip('/')}", lineterm=""))


def detect_drift(expected_hash: str, current_settings: Dict[str, Any]) -> bool:
    """True if the job was edited by someone/something after SMCT recorded `expected_hash`."""
    return canonical_hash(current_settings) != expected_hash
